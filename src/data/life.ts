export type PowerGroup = 1 | 2 | 3 | 4 | 5 | 6;

export function powerOff(group: PowerGroup, hour: number): boolean {
  const slot = Math.floor(hour / 2);
  const start = (group - 1) * 2;
  const hit = (slot - start + 12) % 12;
  return hit === 0 || hit === 1 || hit === 6 || hit === 7;
}

export function kyivHour(date: Date): number {
  const text = new Intl.DateTimeFormat("en-GB", { timeZone: "Europe/Kyiv", hour: "2-digit", hourCycle: "h23" }).format(date);
  return Number(text);
}

