export function seasonTip(date: Date): string {
  const month = Number(
    new Intl.DateTimeFormat("en-GB", { timeZone: "Europe/Kyiv", month: "2-digit" }).format(date),
  );
  if (month === 12 || month <= 2) return "Зима: тримайте термос, пледи і запасні батарейки. Телефон у внутрішній кишені сідає повільніше.";
  if (month <= 4) return "Весна: перевірте, чи не протікає підвал-укриття після дощів, і оновіть воду у валізі.";
  if (month <= 8) return "Літо: вода псується швидше. Міняйте запас раз на кілька днів і майте головний убір.";
  return "Осінь: скоротілий день. Зарядіть ліхтарі, поки світло ще є, і додайте теплий шар у валізу.";
}

export function inCurfew(hour: number, start: number, end: number): boolean {
  if (start === end) return false;
  if (start < end) return hour >= start && hour < end;
  return hour >= start || hour < end;
}

